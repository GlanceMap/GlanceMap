package com.glancemap.glancemapwearos.presentation.features.download

import kotlin.math.cos

/**
 * Simplified OpenAndroMaps clip polygons, captured from the project's public
 * `resources/my_clipbounds` directory. They are bundled so suggestions work
 * without a network request.
 */
internal data class OamDownloadCoveragePolygon(
    val points: List<OamDownloadCoveragePoint>,
) {
    private val south = points.minOf { it.latitude }
    private val west = points.minOf { it.longitude }
    private val north = points.maxOf { it.latitude }
    private val east = points.maxOf { it.longitude }

    fun contains(
        latitude: Double,
        longitude: Double,
    ): Boolean {
        if (latitude !in south..north || longitude !in west..east) return false
        var inside = false
        var previous = points.last()
        points.forEach { current ->
            if (
                (current.latitude > latitude) != (previous.latitude > latitude) &&
                longitude <
                    (previous.longitude - current.longitude) *
                        (latitude - current.latitude) /
                        (previous.latitude - current.latitude) +
                        current.longitude
            ) {
                inside = !inside
            }
            previous = current
        }
        return inside
    }

    fun approximateArea(): Double =
        ((north - south) * (east - west) * cos(Math.toRadians((south + north) / 2.0)))
            .coerceAtLeast(0.0)
}

internal data class OamDownloadCoveragePoint(
    val longitude: Double,
    val latitude: Double,
)

internal object OamDownloadCoverageCatalog {
    private val polygonsByAreaId: Map<String, OamDownloadCoveragePolygon> by lazy {
        OAM_COVERAGE_POLYGON_ROWS
            .trimIndent()
            .lineSequence()
            .filter { it.isNotBlank() }
            .mapNotNull(::parsePolygon)
            .toMap()
    }

    fun areasForLocation(
        areas: List<OamDownloadArea>,
        latitude: Double,
        longitude: Double,
    ): List<OamDownloadArea> {
        if (!isValidCoordinate(latitude, longitude)) return emptyList()
        return areas
            .asSequence()
            .mapNotNull { area ->
                polygonsByAreaId[area.id]
                    ?.takeIf { it.contains(latitude = latitude, longitude = longitude) }
                    ?.let { coverage -> area to coverage.approximateArea() }
            }.sortedBy { (_, area) -> area }
            .map { (area, _) -> area }
            .take(MAX_SUGGESTED_AREAS)
            .toList()
    }

    private fun parsePolygon(row: String): Pair<String, OamDownloadCoveragePolygon>? {
        val separator = row.indexOf('|')
        if (separator <= 0) return null
        val points =
            row
                .substring(separator + 1)
                .split(';')
                .mapNotNull { encodedPoint ->
                    val parts = encodedPoint.split(',')
                    if (parts.size != 2) {
                        null
                    } else {
                        val longitude = parts[0].toDoubleOrNull()
                        val latitude = parts[1].toDoubleOrNull()
                        if (longitude == null || latitude == null) {
                            null
                        } else {
                            OamDownloadCoveragePoint(
                                longitude = longitude,
                                latitude = latitude,
                            )
                        }
                    }
                }
        return row.substring(0, separator) to OamDownloadCoveragePolygon(points)
    }
}

internal fun OamDownloadCatalog.areasForLocation(
    latitude: Double,
    longitude: Double,
): List<OamDownloadArea> =
    OamDownloadCoverageCatalog.areasForLocation(
        areas = areas,
        latitude = latitude,
        longitude = longitude,
    )

private fun isValidCoordinate(
    latitude: Double,
    longitude: Double,
): Boolean =
    latitude.isFinite() &&
        longitude.isFinite() &&
        latitude in -90.0..90.0 &&
        longitude in -180.0..180.0

